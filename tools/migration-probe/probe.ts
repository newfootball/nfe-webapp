const names = [
	"bootstrap",
	"bcrypt-import-login",
	"id-boundaries",
	"tables-schema",
	"compound-unique",
	"case-folded-filter",
	"cursor-counts",
	"relations",
	"moderation-commit",
	"moderation-rollback",
	"cascade-delete",
];
type Result = { status: "passed" | "failed" | "not_run"; detail?: unknown };
const results: Record<string, Result> = Object.fromEntries(
	names.map((n) => [n, { status: "not_run" }]),
);
function safeError(error: unknown) {
	const e = error as {
		code?: number;
		type?: string;
		name?: string;
		stage?: string;
	};
	return { stage: e.stage, code: e.code, type: e.type ?? e.name ?? "Error" };
}
async function check(name: string, run: () => Promise<unknown>) {
	try {
		results[name] = { status: "passed", detail: await run() };
	} catch (error) {
		results[name] = { status: "failed", detail: safeError(error) };
	}
	process.stdout.write(`${name}: ${results[name].status}\n`);
	return results[name].status === "passed";
}
async function rejectsCode(run: () => Promise<unknown>, code: number) {
	try {
		await run();
	} catch (error) {
		assert.equal((error as { code: number }).code, code);
		return;
	}
	throw new Error(`Expected HTTP ${code}`);
}
// A generic 400 can also mean an invalid password/email: require userId specifically.
async function rejectsUserId(run: () => Promise<unknown>) {
	try {
		await run();
	} catch (error) {
		const validation = error as { code: number; type: string; message: string };
		assert.equal(validation.code, 400);
		assert.equal(validation.type, "general_argument_invalid");
		assert.match(validation.message, /^Invalid `userId` param:/);
		return;
	}
	throw new Error("Expected userId validation failure");
}
async function waitFor(run: () => Promise<boolean>) {
	const deadline = Date.now() + 60_000;
	do {
		if (await run()) return;
		await Bun.sleep(500);
	} while (Date.now() < deadline);
	throw new Error("Schema readiness timed out");
}
// Console bootstrap only on the loopback instance generated by local.ts. Never accepts a remote endpoint.
async function bootstrap(): Promise<{
	project: string;
	key: string;
	version: string;
}> {
	if (process.env.NFE_PROBE_LOCAL !== "1")
		throw new Error(
			"Set NFE_PROBE_LOCAL=1 to opt in to synthetic local writes",
		);
	if (!(await Bun.file(`${state}/compose.json`).exists()))
		throw new Error("Run prepare:local and up first");
	const versionResponse = await fetch(`${endpoint}/health/version`);
	assert.equal(versionResponse.status, 200);
	const version = (await versionResponse.json()) as { version: string };
	assert.equal(version.version, "2.6.2");
	const configFile = Bun.file(`${state}/credentials.json`);
	if (await configFile.exists())
		return { ...(await configFile.json()), version: version.version };
	let cookie = "";
	async function consoleRequest(path: string, body?: object) {
		const response = await fetch(`${endpoint}${path}`, {
			method: body ? "POST" : "GET",
			headers: {
				"Content-Type": "application/json",
				"X-Appwrite-Project": "console",
				Origin: "http://localhost",
				...(cookie ? { Cookie: cookie } : {}),
			},
			body: body ? JSON.stringify(body) : undefined,
		});
		const data = (await response.json()) as {
			$id: string;
			secret: string;
			type?: string;
		};
		if (!response.ok)
			throw Object.assign(new Error("Console bootstrap failed"), {
				stage: path,
				code: response.status,
				type: data.type,
			});
		const cookies = response.headers.getSetCookie();
		if (cookies.length) cookie = cookies.map((c) => c.split(";")[0]).join("; ");
		return data;
	}
	async function ensureConsole(
		path: string,
		body: { teamId?: string; projectId?: string; name: string },
	) {
		try {
			return await consoleRequest(`${path}/${body.projectId ?? body.teamId}`);
		} catch (error) {
			if ((error as { code?: number }).code !== 404) throw error;
			return await consoleRequest(path, body);
		}
	}
	const adminFile = Bun.file(`${state}/admin.json`);
	const { password } = (await adminFile.exists())
		? await adminFile.json()
		: { password: `Probe-${crypto.randomUUID()}-Aa1!` };
	await Bun.write(adminFile, JSON.stringify({ password }), { mode: 0o600 });
	try {
		await consoleRequest("/account", {
			userId: "probe-admin",
			email: "probe-admin@example.test",
			password,
			name: "Synthetic probe admin",
		});
	} catch (error) {
		if ((error as { type?: string }).type !== "user_console_count_exceeded")
			throw error;
	}
	await consoleRequest("/account/sessions/email", {
		email: "probe-admin@example.test",
		password,
	});
	const team = await ensureConsole("/teams", {
		teamId: "probe-team",
		name: "Synthetic probe team",
	});
	await ensureConsole("/projects", {
		projectId: "nfe-probe",
		name: "NFE synthetic migration probe",
		teamId: team.$id,
	});
	const key = await consoleRequest("/projects/nfe-probe/keys", {
		keyId: "probe-key",
		name: "Disposable probe only",
		scopes: [
			"users.read",
			"users.write",
			"databases.read",
			"databases.write",
			"tables.read",
			"tables.write",
			"columns.read",
			"columns.write",
			"indexes.read",
			"indexes.write",
			"rows.read",
			"rows.write",
		],
	});
	const credentials = { project: "nfe-probe", key: key.secret };
	await Bun.write(configFile, JSON.stringify(credentials), { mode: 0o600 });
	return { ...credentials, version: version.version };
}
async function main() {
	let credentials:
		| { project: string; key: string; version: string }
		| undefined;
	if (
		!(await check("bootstrap", async () => {
			credentials = await bootstrap();
			return { version: credentials.version };
		}))
	)
		return;
	assert.ok(credentials);
	const projectId = credentials.project;
	const client = new Client()
		.setEndpoint(endpoint)
		.setProject(projectId)
		.setKey(credentials.key);
	const users = new Users(client);
	const db = new TablesDB(client);
	// New namespace each run: no production exports, secrets, or hash written to the report.
	const runId = crypto.randomUUID().replaceAll("-", "").slice(0, 12);
	const databaseId = `probe-${runId}`;
	const userId = `cmigration${runId}`;
	const email = `${userId}@example.test`;
	const password = `Synthetic-${crypto.randomUUID()}!`;
	await check("bcrypt-import-login", async () => {
		const hash = await bcrypt.hash(password, 10); // Same bcryptjs/cost as src/lib/password.ts.
		assert.match(hash, /^\$2[aby]\$10\$/);
		const imported = await users.createBcryptUser({
			userId,
			email,
			password: hash,
		});
		assert.equal(imported.$id, userId);
		const session = await new Account(
			new Client().setEndpoint(endpoint).setProject(projectId),
		).createEmailPasswordSession({ email, password });
		assert.equal(session.userId, userId);
		const webSession = await new WebAccount(
			new WebClient().setEndpoint(endpoint).setProject(projectId),
		).createEmailPasswordSession({ email, password });
		assert.equal(webSession.userId, userId);
		await rejectsCode(
			() =>
				new Account(
					new Client().setEndpoint(endpoint).setProject(projectId),
				).createEmailPasswordSession({
					email,
					password: "Wrong-synthetic-password!",
				}),
			401,
		);
		return {
			bcryptCost: 10,
			serverLogin: true,
			webSdkLoginUnderBun: true,
			browserCookies: "not_run",
		};
	});
	await check("id-boundaries", async () => {
		const hash = await bcrypt.hash(password, 10);
		assert.equal(hash.length, 60);
		assert.match(hash, /^\$2[aby]\$10\$/);
		const ids = [
			`c${runId}123456789012`,
			crypto.randomUUID(),
			`a${"b".repeat(35)}`,
		];
		for (const id of ids) {
			const u = await users.createBcryptUser({
				userId: id,
				email: `${id}@example.test`,
				password: hash,
			});
			assert.equal(u.$id, id);
			await users.delete({ userId: id });
		}
		for (const id of ["a".repeat(37), "_leading", "slash/id"])
			await rejectsUserId(() =>
				users.createBcryptUser({
					userId: id,
					email: "invalid@example.test",
					password: hash,
				}),
			);
		return {
			accepted: ["cuid-shape", "UUID-36", "alphanumeric-36"],
			rejected: ["length-37", "leading-underscore", "slash"],
			negativeFixture: { bcryptCost: 10, hashLength: 60 },
			rejection: {
				code: 400,
				type: "general_argument_invalid",
				parameter: "userId",
			},
		};
	});
	const ref = (tableId: string) => ({ databaseId, tableId });
	const create = (
		tableId: string,
		rowId: string,
		data: Record<string, unknown>,
	) => db.createRow({ ...ref(tableId), rowId, data });
	const schemaReady = await check("tables-schema", async () => {
		await db.create({ databaseId, name: "Disposable synthetic probe" });
		for (const tableId of ["posts", "likes", "reports"])
			await db.createTable({ ...ref(tableId), name: tableId });
		for (const [tableId, keys] of [
			["posts", ["title", "folded", "status"]],
			["likes", ["userId", "postId"]],
			["reports", ["state"]],
		] as const) {
			for (const key of keys)
				await db.createStringColumn({
					...ref(tableId),
					key,
					size: 128,
					required: true,
				});
		}
		await db.createRelationshipColumn({
			...ref("posts"),
			relatedTableId: "reports",
			type: RelationshipType.OneToMany,
			twoWay: true,
			key: "reports",
			twoWayKey: "post",
			onDelete: RelationMutate.Cascade,
		});
		for (const tableId of ["posts", "likes", "reports"])
			await waitFor(async () =>
				(await db.listColumns(ref(tableId))).columns.every(
					(c) => c.status === "available",
				),
			);
		for (const [tableId, key, columns, type] of [
			["likes", "like_pair", ["userId", "postId"], TablesDBIndexType.Unique],
			["posts", "folded_key", ["folded"], TablesDBIndexType.Key],
			["posts", "status_key", ["status"], TablesDBIndexType.Key],
		] as const) {
			await db.createIndex({
				...ref(tableId),
				key,
				columns: [...columns],
				type,
			});
			await waitFor(
				async () =>
					(await db.getIndex({ ...ref(tableId), key })).status === "available",
			);
		}
		for (let i = 1; i <= 5; i++)
			await create("posts", `post-${i}`, {
				title: i <= 2 ? "Équipe PARIS" : `Post ${i}`,
				folded: i <= 2 ? "équipe paris" : `post ${i}`,
				status: "published",
			});
		return { databaseId, tables: 3 };
	});
	if (schemaReady) {
		await check("compound-unique", async () => {
			await create("likes", "like-1", { userId, postId: "post-1" });
			await rejectsCode(
				() => create("likes", "like-2", { userId, postId: "post-1" }),
				409,
			);
			await create("likes", "like-3", { userId, postId: "post-2" });
		});
		await check("case-folded-filter", async () => {
			const normalized = "ÉQUIPE Paris"
				.normalize("NFC")
				.toLocaleLowerCase("fr");
			const list = await db.listRows({
				...ref("posts"),
				queries: [Query.equal("folded", normalized)],
				total: true,
			});
			assert.equal(list.total, 2);
			assert.equal(list.rows.length, 2);
			const substring = await db.listRows({
				...ref("posts"),
				queries: [
					Query.contains("folded", "QUIPE PAR".toLocaleLowerCase("fr")),
				],
				total: true,
			});
			assert.equal(substring.total, 2);
			const nativeCase = await db.listRows({
				...ref("posts"),
				queries: [Query.contains("title", "éQUIPE par")],
				total: true,
			});
			return {
				strategy:
					"materialized NFC + fr lowercase, indexed equality and substring",
				nativeMixedCaseContainsCount: nativeCase.total,
				accentInsensitive: "not_run",
			};
		});
		await check("cursor-counts", async () => {
			const ids: string[] = [];
			let cursor: string | undefined;
			for (let page = 0; page < 4; page++) {
				const list = await db.listRows({
					...ref("posts"),
					queries: [
						Query.orderAsc("$id"),
						Query.limit(2),
						...(cursor ? [Query.cursorAfter(cursor)] : []),
					],
					total: true,
				});
				assert.equal(list.total, 5);
				ids.push(...list.rows.map((r) => r.$id));
				if (list.rows.length < 2) break;
				cursor = list.rows.at(-1)?.$id;
			}
			assert.deepEqual(ids, ["post-1", "post-2", "post-3", "post-4", "post-5"]);
			return {
				ids,
				ordering: "$id ascending, immutable unique tiebreaker",
				concurrentMutations: "not_run",
			};
		});
		const related = await check("relations", async () => {
			await create("reports", "report-1", { state: "open", post: "post-1" });
			const row = await db.getRow({
				...ref("posts"),
				rowId: "post-1",
				queries: [Query.select(["*", "reports.*"])],
			});
			assert.equal(row.reports.length, 1);
			assert.equal(row.reports[0].$id, "report-1");
			return {
				relation: "posts one-to-many reports; explicit select expansion",
			};
		});
		if (related) {
			await check("moderation-commit", async () => {
				const tx = await db.createTransaction({ ttl: 60 });
				await db.updateRow({
					...ref("posts"),
					rowId: "post-1",
					data: { status: "hidden" },
					transactionId: tx.$id,
				});
				await db.updateRow({
					...ref("reports"),
					rowId: "report-1",
					data: { state: "resolved" },
					transactionId: tx.$id,
				});
				assert.equal(
					(await db.getRow({ ...ref("posts"), rowId: "post-1" })).status,
					"published",
				);
				await db.updateTransaction({ transactionId: tx.$id, commit: true });
				assert.equal(
					(await db.getRow({ ...ref("posts"), rowId: "post-1" })).status,
					"hidden",
				);
				assert.equal(
					(await db.getRow({ ...ref("reports"), rowId: "report-1" })).state,
					"resolved",
				);
			});
			await check("moderation-rollback", async () => {
				const before = (await db.getRow({ ...ref("posts"), rowId: "post-2" }))
					.status;
				const tx = await db.createTransaction({ ttl: 60 });
				await db.updateRow({
					...ref("posts"),
					rowId: "post-2",
					data: { status: "hidden" },
					transactionId: tx.$id,
				});
				await db.updateTransaction({ transactionId: tx.$id, rollback: true });
				assert.equal(
					(await db.getRow({ ...ref("posts"), rowId: "post-2" })).status,
					before,
				);
				return { explicitRollback: true, automaticConflictRollback: "not_run" };
			});
			await check("cascade-delete", async () => {
				await db.deleteRow({ ...ref("posts"), rowId: "post-1" });
				await waitFor(async () => {
					try {
						await db.getRow({ ...ref("reports"), rowId: "report-1" });
						return false;
					} catch (e) {
						if ((e as { code: number }).code === 404) return true;
						throw e;
					}
				});
				return {
					deletedParentAndReport: true,
					authUserAndB2ObjectCascade: "not_run",
				};
			});
		}
	}
	// The entire instance is discarded with `down`; keep fixtures until then for diagnosis.
}
try {
	await main();
} catch (error) {
	results.unexpected = { status: "failed", detail: safeError(error) };
}
await mkdir(`${import.meta.dir}/results`, { recursive: true });
const report = {
	timestamp: new Date().toISOString(),
	endpoint,
	matrix: {
		appwrite: "2.6.2",
		serverSdk: "31.1.0",
		webSdk: "29.2.0",
		bun: Bun.version,
	},
	results,
	b2: {
		status: "not_run",
		reason:
			"No confirmed real B2 test bucket or credentials; no remote upload attempted",
	},
};
await Bun.write(
	`${import.meta.dir}/results/latest.json`,
	JSON.stringify(report, null, 2),
);
if (Object.values(results).some((r) => r.status !== "passed"))
	process.exitCode = 1;
